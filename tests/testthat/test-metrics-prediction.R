test_that("individual prediction metrics have known values", {
  obs <- 1:3
  pred <- c(1, 3, 2)
  expect_equal(bias(obs, pred), 0)
  expect_equal(mae(obs, pred), 2 / 3)
  expect_equal(mse(obs, pred), 2 / 3)
  expect_equal(rmse(obs, pred), sqrt(2 / 3))
  expect_equal(nrmse(obs, pred), sqrt(2 / 3) / sd(obs))
  expect_equal(crmse(obs, pred), sqrt(2 / 3))
  expect_equal(correlation(obs, pred), 0.5)
  expect_equal(r2(obs, pred), 0.25)
  expect_equal(nse(obs, pred), 0)
  expect_equal(mec(obs, pred), nse(obs, pred))
  expect_equal(R2(obs, pred), nse(obs, pred))
  expect_equal(sd_ratio(obs, pred), 1)
  expect_equal(ccc(obs, pred), 0.5)
})

test_that("extended prediction metrics have expected values", {
  obs <- c(1, 2, 3); pred <- c(1, 3, 2)
  expect_equal(mdae(obs, pred), 1)
  expect_equal(rpd(obs, pred), 1 / nrmse(obs, pred))
  expect_equal(rpiq(obs, pred), stats::IQR(obs) / rmse(obs, pred))
  expect_equal(sep(obs, pred), 1)
  expect_equal(rae(obs, pred), 1)
  expect_equal(mpe(obs, pred), 100 * mean((obs - pred) / obs))
  expect_equal(rrmse(obs, pred), 100 * rmse(obs, pred) / mean(obs))
  expect_equal(willmott_d(obs, obs), 1)
  expect_equal(pinball_loss(obs, pred, .5), mae(obs, pred) / 2)
  expect_true(is.finite(kge(obs, pred)))
  expect_warning(expect_true(is.na(mape(c(0, 1), c(0, 1)))), "zero values")
  expect_warning(expect_true(is.na(mpe(c(0, 1), c(0, 1)))), "zero values")
  expect_warning(expect_true(is.na(rrmse(c(-1, 1), c(-1, 1)))), "mean of the observations is zero")
  expect_warning(expect_true(is.na(msle(c(-1, 1), c(0, 1)))), "negative values")
})

test_that("prediction metrics handle perfect, biased and missing predictions", {
  obs <- 1:4
  expect_equal(bias(obs, obs), 0)
  expect_equal(rmse(obs, obs), 0)
  expect_equal(nse(obs, obs), 1)
  expect_equal(ccc(obs, obs), 1)
  expect_equal(bias(obs, obs + 2), -2)
  expect_equal(mae(obs, obs + 2), 2)
  expect_equal(mae(c(1, NA, 3), c(1, 2, 2)), mae(c(1, 3), c(1, 2)))
  expect_warning(expect_true(is.na(mae(c(1, NA, 3), c(1, 2, 2), na.rm = FALSE))),
                 "MAE is undefined because inputs contain missing values")
  expect_equal(rmse(c(1, NA, 3), c(1, 2, 2)), rmse(c(1, 3), c(1, 2)))
  expect_warning(expect_true(is.na(rmse(c(1, NA, 3), c(1, 2, 2), na.rm = FALSE))),
                 "RMSE is undefined because inputs contain missing values")
})

test_that("prediction metric validation and edge cases are explicit", {
  expect_error(rmse(1:2, 1:3), "same length")
  expect_error(rmse(1:3, c(1, Inf, 3)), "infinite")
  expect_warning(expect_true(is.na(correlation(1:3, rep(2, 3)))), "predictions have zero variance")
  expect_warning(expect_true(is.na(nrmse(rep(1, 3), 1:3))), "observations have zero variance")
  expect_warning(expect_true(is.na(nse(rep(1, 3), 1:3))), "observations have zero variance")
})

test_that("model_metrics exposes one column per statistic", {
  got <- model_metrics(list(a = 1:3, b = c(1, 3, 2)), 1:3)
  expect_equal(got$model, c("a", "b"))
  expect_equal(got$rmse, c(0, sqrt(2 / 3)))
  expect_false(any(c("ME", "RMSE", "NSE", "MEC", "nse", "rhoC") %in% names(got)))
  expect_equal(got$R2, c(1, 0))
  expect_equal(got$ccc, c(1, 0.5))
  extended <- model_metrics(list(a = 1:3), 1:3, extended = TRUE)
  expect_true(all(c("mdae", "rpd", "rpiq", "sep", "rer", "mape", "mpe", "smape", "msle", "rmsle", "rae", "rrmse", "willmott_d", "kge", "R2") %in% names(extended)))
})
